import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def raster(source, face, size, weight=None):
    font = ImageFont.truetype(str(source), size)
    if weight is not None:
        axes = {b"Weight": weight, b"Optical size": size}
        font.set_variation_by_axes([axes.get(axis["name"], axis["default"])
                                    for axis in font.get_variation_axes()])
    bitmap, glyphs = [], []
    for code in range(32, 127):
        ch = chr(code)
        x, y, right, bottom = font.getbbox(ch, anchor="ls")
        width, height = right - x, bottom - y
        advance = max(round(font.getlength(ch)), right)
        glyphs.append((len(bitmap), width, height, advance, x, y))
        if not width or not height:
            continue
        image = Image.new("L", (width, height))
        ImageDraw.Draw(image).text((-x, -y), ch, font=font, fill=255, anchor="ls")
        coverage = [(value * 3 + 127) // 255 for value in image.tobytes()]
        for i in range(0, len(coverage), 4):
            bitmap.append(sum(value << (6 - j * 2) for j, value in enumerate(coverage[i:i + 4])))
    rows = [", ".join(f"0x{x:02X}" for x in bitmap[i:i + 24]) for i in range(0, len(bitmap), 24)]
    header = [f"inline constexpr uint8_t {face}_bitmap[] = {{"]
    header += [f"\t{row}," for row in rows]
    header += ["};", f"inline constexpr Glyph {face}_glyphs[] = {{"]
    header += ["\t{" + ", ".join(map(str, glyph)) + "}," for glyph in glyphs]
    header += ["};", ""]
    return "\n".join(header)


def export(destination, source_notice, license_file, faces):
    header = (f"// Generated by tools/export-settings-font.py from {source_notice}.\n"
              f"// Font data is distributed under the SIL OFL 1.1; see {license_file}.\n")
    destination.write_text(header + "\n".join(faces), encoding="ascii", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, nargs="?", help="extras/otf from the Inter release archive")
    parser.add_argument("--dm-sans", type=Path, help="DM Sans variable TTF from Google Fonts")
    args = parser.parse_args()
    if bool(args.source) == bool(args.dm_sans):
        parser.error("provide either the Inter OTF folder or --dm-sans with the variable TTF")
    output = Path(__file__).resolve().parents[1] / "OTA-bot-Mochi/src/ui/fonts"
    output.mkdir(exist_ok=True)
    faces = (("Medium", 18, 500), ("SemiBold", 22, 600))
    if args.dm_sans:
        for name, size, weight in faces:
            face = name.lower()
            export(output / f"mochi_dm_sans_{face}.h", "Google Fonts DM Sans", "OFL-DM-Sans.txt",
                   [raster(args.dm_sans, f"dm_{face}", size, weight)])
    else:
        for name, size, _ in faces:
            face = name.lower()
            export(output / f"mochi_sans_{face}.h", "the Inter 4.1 release", "OFL-Inter.txt",
                   [raster(args.source / f"Inter-{name}.otf", face, size)])
